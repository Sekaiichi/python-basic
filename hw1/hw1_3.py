# Задание 3: Плитка шоколада
"""
    Пользователь вводит длину и ширину плитки шоколада,
    а также размер куска, который хочет отломить.
    Программа должна вычислить - можно ли совершить подобный разлом или нет,
    если учесть, что ломать можно только по прямой.
"""
def can_break_chocolate(n: int, m: int, k: int) -> bool:
    # Нельзя отломить 0, отрицательное или всю плитку
    if k <= 0 or k >= n * m:
        return False
    # Один прямой разлом: k должно делиться на n или на m
    return (k % n == 0) or (k % m == 0)


# Ввод пользователя
n = int(input("Введите длину плитки: "))
m = int(input("Введите ширину плитки: "))
k = int(input("Введите размер куска (кол-во долек): "))

print(can_break_chocolate(n, m, k))
