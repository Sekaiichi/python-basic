# 2. Написать функцию для ввода из консоли целого числа.
# Если введено не число, функция должна вывести соответствующее сообщение и предложить ввести значение заново — до тех пор, пока пользователь не введёт корректное число.

def input_integer():
    while True:
        try:
            number = int(input("Введите целое число: "))
            return number
        except ValueError:
            print("Ошибка: введено не целое число. Попробуйте ещё раз.")


result = input_integer()

print("Вы ввели число:", result)